import { Pool } from "pg";

const pool = new Pool({ connectionString: process.env.DATABASE_URL, max: 3, connectionTimeoutMillis: 5000 });
let schemaReady;
async function ensureSchema() {
  if (!schemaReady) schemaReady = pool.query(`
    CREATE TABLE IF NOT EXISTS homepage_content (
      section_key VARCHAR(40) PRIMARY KEY,
      content JSONB NOT NULL DEFAULT '{}'::jsonb,
      updated_by BIGINT,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
    CREATE TABLE IF NOT EXISTS newsletter_subscribers (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      email VARCHAR(190) NOT NULL UNIQUE,
      source VARCHAR(40) NOT NULL DEFAULT 'homepage',
      status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK(status IN ('active','unsubscribed')),
      consent_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
    CREATE TABLE IF NOT EXISTS blog_posts (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      slug VARCHAR(180) NOT NULL UNIQUE,
      title VARCHAR(180) NOT NULL,
      excerpt VARCHAR(500) NOT NULL DEFAULT '',
      body TEXT NOT NULL DEFAULT '',
      cover_image TEXT,
      status VARCHAR(20) NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','published','archived')),
      published_at TIMESTAMPTZ,
      created_by BIGINT,
      updated_by BIGINT,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
    CREATE INDEX IF NOT EXISTS blog_posts_public_idx ON blog_posts(status,published_at DESC) WHERE status='published';
    CREATE INDEX IF NOT EXISTS newsletter_subscribers_active_idx ON newsletter_subscribers(status,created_at DESC);
  `).catch(error => { schemaReady = null; throw error; });
  return schemaReady;
}
function send(res,status,value) {
  res.writeHead(status,{"Content-Type":"application/json; charset=utf-8","Cache-Control":"no-store"});
  res.end(JSON.stringify(value));
}
async function readBody(req) {
  let raw="";
  for await (const chunk of req) { raw+=chunk; if(raw.length>300000) throw Object.assign(new Error("حجم درخواست بیش از حد مجاز است."),{status:413}); }
  try { return raw ? JSON.parse(raw) : {}; } catch { throw Object.assign(new Error("ساختار درخواست معتبر نیست."),{status:400}); }
}
function cleanText(value,max) {
  if(typeof value!=="string") return null;
  const text=value.replace(/\u0000/g,"").trim();
  return text.length<=max ? text : null;
}
const sections = new Set(["hero","features","plans","partners","how","trust","faq","blog","newsletter","cta","footer"]);
const fields = new Set(["title","description","eyebrow","feature1Title","feature1Description","feature2Title","feature2Description","feature3Title","feature3Description","feature4Title","feature4Description","feature5Title","feature5Description"]);
async function audit(admin,action,details) {
  try {
    await pool.query("INSERT INTO audit_logs(user_id,event_type,details) VALUES($1,$2,$3)",[Number(admin.sub),action,JSON.stringify(details)]);
  } catch (error) {
    if(error.code!=="42P01") throw error;
  }
}
export async function handleSiteContent(req,res,url,admin) {
  const route=url.pathname;
  try { await ensureSchema(); }
  catch(error) { console.error("site_content_schema_error",error.code||error.message); return send(res,503,{message:"سرویس محتوای سایت موقتاً در دسترس نیست."}); }

  if(req.method==="GET" && route==="/api/v1/site-content/homepage") {
    const q=await pool.query("SELECT section_key,content FROM homepage_content ORDER BY section_key");
    return send(res,200,{data:Object.fromEntries(q.rows.map(row=>[row.section_key,row.content]))});
  }
  if(req.method==="POST" && route==="/api/v1/newsletter/subscribe") {
    const b=await readBody(req), email=String(b.email||"").trim().toLowerCase();
    if(email.length>190 || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) return send(res,400,{message:"نشانی ایمیل معتبر نیست."});
    const source=["homepage","blog","footer"].includes(String(b.source||""))?String(b.source):"homepage";
    await pool.query("INSERT INTO newsletter_subscribers(email,source,status,consent_at,updated_at) VALUES($1,$2,'active',NOW(),NOW()) ON CONFLICT(email) DO UPDATE SET source=EXCLUDED.source,status='active',consent_at=NOW(),updated_at=NOW()",[email,source]);
    return send(res,200,{ok:true,message:"عضویت شما در خبرنامه ثبت شد."});
  }
  if(req.method==="GET" && route==="/api/v1/blog/posts") {
    const limit=Math.min(12,Math.max(1,Number(url.searchParams.get("limit"))||3));
    const q=await pool.query("SELECT id,slug,title,excerpt,cover_image AS \"coverImage\",published_at AS \"publishedAt\" FROM blog_posts WHERE status='published' AND published_at<=NOW() ORDER BY published_at DESC,id DESC LIMIT $1",[limit]);
    return send(res,200,{data:q.rows});
  }
  if(req.method==="GET" && route.startsWith("/api/v1/blog/posts/")) {
    const slug=decodeURIComponent(route.slice("/api/v1/blog/posts/".length));
    const q=await pool.query("SELECT id,slug,title,excerpt,body,cover_image AS \"coverImage\",published_at AS \"publishedAt\" FROM blog_posts WHERE slug=$1 AND status='published' AND published_at<=NOW() LIMIT 1",[slug]);
    return q.rowCount?send(res,200,{data:q.rows[0]}):send(res,404,{message:"مطلب پیدا نشد."});
  }
  if(route.startsWith("/api/v1/admin/site-content/") || route.startsWith("/api/v1/admin/blog/")) {
    if(!admin) return send(res,403,{message:"دسترسی مدیر لازم است."});
  }
  if(req.method==="PUT" && route==="/api/v1/admin/site-content/homepage") {
    const b=await readBody(req),section=String(b.section||"");
    if(!sections.has(section)||!b.content||typeof b.content!=="object"||Array.isArray(b.content)) return send(res,400,{message:"بخش یا محتوای ارسالی معتبر نیست."});
    const clean={};
    for(const [key,value] of Object.entries(b.content)) {
      if(!fields.has(key)) return send(res,400,{message:"فیلد ارسالی مجاز نیست."});
      const text=cleanText(value,1200); if(text===null) return send(res,400,{message:"متن باید حداکثر ۱۲۰۰ نویسه باشد."}); clean[key]=text;
    }
    if(!Object.keys(clean).length) return send(res,400,{message:"محتوایی برای ذخیره ارسال نشده است."});
    const q=await pool.query("INSERT INTO homepage_content(section_key,content,updated_by,updated_at) VALUES($1,$2::jsonb,$3,NOW()) ON CONFLICT(section_key) DO UPDATE SET content=homepage_content.content || EXCLUDED.content,updated_by=EXCLUDED.updated_by,updated_at=NOW() RETURNING section_key,content,updated_at",[section,JSON.stringify(clean),Number(admin.sub)]);
    await audit(admin,"homepage.content.updated",{section,fields:Object.keys(clean)});
    return send(res,200,{ok:true,data:q.rows[0]});
  }
  if(req.method==="GET" && route==="/api/v1/admin/blog/posts") {
    const q=await pool.query("SELECT id,slug,title,excerpt,status,published_at AS \"publishedAt\",updated_at AS \"updatedAt\" FROM blog_posts ORDER BY updated_at DESC LIMIT 200");
    return send(res,200,{data:q.rows});
  }
  if(req.method==="POST" && route==="/api/v1/admin/blog/posts") {
    const b=await readBody(req),title=cleanText(b.title,180),excerpt=cleanText(b.excerpt||"",500),body=cleanText(b.body||"",100000);
    const slug=String(b.slug||"").trim().toLowerCase().replace(/[^a-z0-9-]/g,"-").replace(/-+/g,"-").replace(/^-|-$/g,"").slice(0,180);
    const status=b.status==="published"?"published":"draft";
    if(!title||title.length<3||!excerpt||body===null||!slug) return send(res,400,{message:"عنوان، نشانی یا متن مطلب معتبر نیست."});
    const q=await pool.query("INSERT INTO blog_posts(slug,title,excerpt,body,status,published_at,created_by,updated_by) VALUES($1,$2,$3,$4,$5,CASE WHEN $5='published' THEN NOW() ELSE NULL END,$6,$6) RETURNING id,slug,title,excerpt,status,published_at AS \"publishedAt\"",[slug,title,excerpt,body,status,Number(admin.sub)]);
    await audit(admin,"blog.post.created",{postId:q.rows[0].id,status});
    return send(res,201,{data:q.rows[0]});
  }
  const idMatch=route.match(/^\/api\/v1\/admin\/blog\/posts\/(\d+)$/);
  if(idMatch && req.method==="PUT") {
    const id=Number(idMatch[1]),b=await readBody(req),title=cleanText(b.title,180),excerpt=cleanText(b.excerpt||"",500),body=cleanText(b.body||"",100000);
    const status=["draft","published","archived"].includes(b.status)?b.status:"draft";
    if(!title||title.length<3||!excerpt||body===null) return send(res,400,{message:"عنوان یا متن مطلب معتبر نیست."});
    const q=await pool.query("UPDATE blog_posts SET title=$2,excerpt=$3,body=$4,status=$5,published_at=CASE WHEN $5='published' THEN COALESCE(published_at,NOW()) ELSE NULL END,updated_by=$6,updated_at=NOW() WHERE id=$1 RETURNING id,slug,title,excerpt,status,published_at AS \"publishedAt\"",[id,title,excerpt,body,status,Number(admin.sub)]);
    if(!q.rowCount) return send(res,404,{message:"مطلب پیدا نشد."});
    await audit(admin,"blog.post.updated",{postId:id,status});
    return send(res,200,{data:q.rows[0]});
  }
  if(idMatch && req.method==="DELETE") {
    const id=Number(idMatch[1]),q=await pool.query("UPDATE blog_posts SET status='archived',updated_by=$2,updated_at=NOW() WHERE id=$1 RETURNING id",[id,Number(admin.sub)]);
    if(!q.rowCount) return send(res,404,{message:"مطلب پیدا نشد."});
    await audit(admin,"blog.post.archived",{postId:id});
    return send(res,200,{ok:true});
  }
  return false;
}
