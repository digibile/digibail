import { readFileSync, writeFileSync } from "node:fs";

const sources = [
  { file: "database/mysql/schema-main.sql", prefix: "main__", label: "main" },
  { file: "database/mysql/schema-bluvamdb.sql", prefix: "bluvamdb__", label: "bluvamdb" },
  { file: "database/mysql/schema-transfer.sql", prefix: "transferdb__", label: "transfer" }
];

function quote(name) { return "`" + name.replace(/\`/g, "") + "`"; }
function transform(source) {
  let sql = readFileSync(source.file, "utf8");
  const tables = [...sql.matchAll(/CREATE\s+TABLE\s+`([^\`]+)`/gi)].map(m => m[1]);
  if (!tables.length) throw new Error("No CREATE TABLE statements in " + source.file);

  for (const table of tables) {
    const target = source.label === "main" ? table : source.prefix + table;
    const qFrom = quote(table);
    const qTo = quote(target);
    sql = sql.replace(new RegExp("(CREATE\\s+TABLE\\s+)" + qFrom.replace(/[.*+?^${}()|[\\]\\\\]/g, "\\\\$&"), "gi"), "$1" + qTo);
    sql = sql.replace(new RegExp("(ALTER\\s+TABLE\\s+)" + qFrom.replace(/[.*+?^${}()|[\\]\\\\]/g, "\\\\$&"), "gi"), "$1" + qTo);
    sql = sql.replace(new RegExp("(REFERENCES\\s+)" + qFrom.replace(/[.*+?^${}()|[\\]\\\\]/g, "\\\\$&"), "gi"), "$1" + qTo);
  }
  const constraintPrefix = source.prefix;
  sql = sql.replace(/(CONSTRAINT\\s+`)([^`]+)(`)/gi, "$1" + constraintPrefix + "$2$3");
  sql = sql.replace(/Target database: [^\\r\\n]+/g, "Target database: vamcitydigibilepay");
  sql = sql.replace(/create\/select it in DirectAdmin or cPanel before import/gi, "create/select it once in DirectAdmin or cPanel before import");
  return { sql, tables: tables.map(t => source.label === "main" ? t : source.prefix + t) };
}

const parts = sources.map(transform);
const allTables = parts.flatMap(p => p.tables);
const duplicates = allTables.filter((t, i) => allTables.indexOf(t) !== i);
if (duplicates.length) throw new Error("Duplicate target table names: " + [...new Set(duplicates)].join(", "));
if (allTables.length !== 156) throw new Error("Expected 156 tables, found " + allTables.length);

const output = [
  "-- Unified VamCity database: all three SQL Server sources in ONE MariaDB/MySQL database.",
  "-- Generated by scripts/build-vamcity-unified-schema.mjs. Do not edit by hand.",
  "-- Source data is imported separately; this file contains DDL only.",
  "-- Target database name: vamcitydigibilepay",
  "CREATE DATABASE IF NOT EXISTS `vamcitydigibilepay` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;",
  "USE `vamcitydigibilepay`;",
  "SET NAMES utf8mb4;",
  "SET FOREIGN_KEY_CHECKS=0;",
  ...parts.map(p => p.sql),
  "SET FOREIGN_KEY_CHECKS=1;",
  ""
].join("\n\n");

writeFileSync("database/mysql/vamcitydigibilepay.sql", output);
console.log(JSON.stringify({ target: "vamcitydigibilepay", tables: allTables.length, sources: parts.map(p => p.tables.length), output: "database/mysql/vamcitydigibilepay.sql" }));
