import { readFileSync, writeFileSync } from "node:fs";

const sources = [
  { file: "database/mysql/schema-main.sql", prefix: "main__", label: "main" },
  { file: "database/mysql/schema-bluvamdb.sql", prefix: "bluvamdb__", label: "bluvamdb" },
  { file: "database/mysql/schema-transfer.sql", prefix: "transferdb__", label: "transfer" }
];

function transform(source) {
  let sql = readFileSync(source.file, "utf8");
  const tables = [...sql.matchAll(/CREATE\s+TABLE\s+\`([^\`]+)\`/gi)].map(match => match[1]);
  if (!tables.length) throw new Error("No CREATE TABLE statements in " + source.file);
  for (const table of tables) {
    const target = source.label === "main" ? table : source.prefix + table;
    const from = "\`" + table + "\`";
    const to = "\`" + target + "\`";
    for (const clause of ["CREATE TABLE ", "ALTER TABLE ", "REFERENCES "]) {
      sql = sql.split(clause + from).join(clause + to);
    }
  }
  sql = sql.replace(/(CONSTRAINT\s+\`)([^\`]+)(\`)/gi,
    (_, before, name, after) => before + source.prefix + name + after);
  sql = sql.replace(/Target database: [^\r\n]+/g, "Target database: vamcitydigibilepay");
  return { sql, tables: tables.map(name => source.label === "main" ? name : source.prefix + name) };
}

const parts = sources.map(transform);
const allTables = parts.flatMap(part => part.tables);
if (allTables.length !== 156 || new Set(allTables).size !== 156) {
  throw new Error("Expected 156 unique tables; found " + allTables.length);
}

const output = [
  "-- Unified VamCity database: all three SQL Server sources in ONE MariaDB/MySQL database.",
  "-- Generated by scripts/build-vamcity-unified-schema.mjs. Do not edit by hand.",
  "-- DDL only. Source records must be imported and reconciled separately.",
  "CREATE DATABASE IF NOT EXISTS \`vamcitydigibilepay\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;",
  "USE \`vamcitydigibilepay\`;",
  "SET NAMES utf8mb4;",
  "SET FOREIGN_KEY_CHECKS=0;",
  ...parts.map(part => part.sql),
  "SET FOREIGN_KEY_CHECKS=1;",
  ""
].join("\n\n");

writeFileSync("database/mysql/vamcitydigibilepay.sql", output);
console.log(JSON.stringify({ database: "vamcitydigibilepay", tables: allTables.length, perSource: parts.map(part => part.tables.length) }));
